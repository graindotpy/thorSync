export const getMockGameDetail = (gameId: string): GameDetail | undefined => {
  const game = mockGames.find((item) => item.id === gameId)
  if (!game) return undefined
  return {
    ...game,
    revisions: revisionsFor(game),
    bindings: mockEndpoints.map((endpoint) => ({
      id: `${game.id}-${endpoint.id}`,
      endpointId: endpoint.id,
      endpointName: endpoint.name,
      relativePath: `${game.title}.${endpoint.kind === 'thor' ? 'srm' : 'sav'}`,
      extension: endpoint.kind === 'thor' ? '.srm' : '.sav',
      baselineRevisionId: game.currentRevisionId,
      deliveryState:
        game.deliveryState === 'missing' && endpoint.kind === 'thor'
          ? 'missing'
          : game.deliveryState,
      lastDeliveredAt: game.deliveryState === 'missing' ? null : game.updatedAt,
    })),
  }
}

